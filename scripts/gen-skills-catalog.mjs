#!/usr/bin/env node
/**
 * Generates docs/skills-catalog.md from .claude/skills/.
 *
 * Generated rather than written, because a hand-kept catalogue goes stale the
 * first time somebody runs sync-sap-skills.sh and does not think to update it.
 * The purposes come from each skill's own front matter, so the catalogue says
 * what the skill says about itself.
 *
 * Usage:  node scripts/gen-skills-catalog.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SKILLS = join(ROOT, ".claude/skills");
const OUT = join(ROOT, "docs/skills-catalog.md");

/**
 * Sections, in order, each claiming skills by pattern.
 *
 * First match wins, so the specific patterns come before the general ones —
 * `sap-btp-cloud-identity-services` is security before it is BTP.
 */
const SECTIONS = [
  ["D-LAB-5", /^dlab5-/, "Written here, for this repository."],
  [
    "ABAP and SAP development",
    /^(sap-abap|sap-cap|sap-fiori|sap-sqlscript|sapui5)/,
    "The languages and frameworks SAP applications are written in.",
  ],
  [
    "BTP and platform engineering",
    /^sap-btp/,
    "The platform those applications are extended and integrated on.",
  ],
  [
    "Data, analytics and AI",
    /^(sap-hana|sap-datasphere|sap-bw|sap-sac|sap-ai|sap-cloud-sdk-ai|sap-rpt)/,
    "Where SAP data is stored, modelled, reported on and predicted from.",
  ],
  [
    "API and security",
    /^(sap-api|sap-dependency)/,
    "Interface style, policy and supply-chain security.",
  ],
  [
    "Tooling and automation",
    /^(sap-browser|sap-.*-cli|sap-.*-automation|sap-.*-linter)/,
    "Driving SAP tools and interfaces from outside them.",
  ],
  // Kept, but empty is the goal: a skill landing here means a heading is
  // missing rather than that the skill is miscellaneous.
  ["Unclassified", /./, "No heading above fits. Add one."],
];

/** The front matter of a SKILL.md — name, description, licence, maintainer. */
function frontMatter(path) {
  const text = readFileSync(path, "utf8");
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!match) return null;
  const body = match[1];

  const scalar = (key) => {
    const line = new RegExp(`^${key}:\\s*(.*)$`, "m").exec(body);
    if (!line) return null;
    return line[1].replace(/^["']|["']$/g, "").trim() || null;
  };

  // `description:` is a scalar on some skills and a `|` block on others.
  let description = scalar("description");
  if (!description || description === "|") {
    const block = /^description:\s*\|?\s*\r?\n([\s\S]*?)(?=^\S)/m.exec(body);
    description = block ? block[1].replace(/\s+/g, " ").trim() : "";
  }

  return {
    name: scalar("name"),
    description,
    license: scalar("license"),
    maintainer: /maintainer:\s*"?([^"\n]+)"?/.exec(body)?.[1]?.trim() ?? null,
  };
}

/**
 * One sentence, because a table cell is one line.
 *
 * These descriptions are written for a model deciding whether to open the
 * skill, so they are long and keyword-dense. The first sentence is the part a
 * person scanning a table needs.
 */
function purpose(description) {
  const first = /^(.*?[.!?])(\s|$)/.exec(description);
  const one = (first ? first[1] : description).trim();
  return one.length > 160 ? `${one.slice(0, 157).trimEnd()}…` : one;
}

const skills = readdirSync(SKILLS, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => {
    const fm = frontMatter(join(SKILLS, e.name, "SKILL.md"));
    return fm && fm.name ? { dir: e.name, ...fm } : null;
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name));

const claimed = new Set();
const grouped = SECTIONS.map(([title, pattern, blurb]) => {
  const members = skills.filter(
    (s) => !claimed.has(s.dir) && pattern.test(s.dir) && claimed.add(s.dir)
  );
  return { title, blurb, members };
}).filter((g) => g.members.length > 0);

const licences = [...new Set(skills.map((s) => s.license).filter(Boolean))];
const maintainers = [...new Set(skills.map((s) => s.maintainer).filter(Boolean))];

const lines = [
  "<!-- Generated by scripts/gen-skills-catalog.mjs. Do not edit by hand. -->",
  "",
  "# Skills catalogue",
  "",
  `${skills.length} skills in \`.claude/skills/\`. Use the narrowest one that fits;`,
  "open its `SKILL.md` for the full workflow rather than working from the line",
  "below.",
  "",
  "Regenerate with `npm run gen:skills-catalog` after adding a skill or running",
  "`scripts/sync-sap-skills.sh`.",
  "",
  "## Contents",
  "",
  ...grouped.map(
    (g) =>
      `- [${g.title}](#${g.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}) — ${g.members.length}`
  ),
  "",
];

for (const g of grouped) {
  lines.push(`## ${g.title}`, "", g.blurb, "", "| Skill | Purpose |", "| --- | --- |");
  for (const s of g.members) {
    lines.push(
      `| [${s.name}](../.claude/skills/${s.dir}/SKILL.md) | ${purpose(s.description)} |`
    );
  }
  lines.push("");
}

lines.push(
  "## Licensing",
  "",
  `Licences present: ${licences.join(", ") || "unstated"}.`,
  "",
  `The SAP skills are maintained by ${maintainers.filter((m) => m !== "Systems LAB 5").join(", ") || "their authors"}`,
  "and are GPL-3.0 — which is why this repository is GPL-3.0-or-later rather",
  "than MIT. `NOTICE` records where they came from and the one modification",
  "made to them.",
  ""
);

writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${OUT}`);
console.log(`  ${skills.length} skills in ${grouped.length} sections`);
for (const g of grouped) console.log(`    ${String(g.members.length).padStart(3)}  ${g.title}`);
